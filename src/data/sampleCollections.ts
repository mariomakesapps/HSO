import type { CollectionSummary } from "@/store/collections";

const now = Date.now();
const day = 24 * 60 * 60 * 1000;

function sampleCollection(
  id: string,
  title: string,
  owner: string,
  description: string,
  tags: string[],
  intended_majors: string[],
  categories: string[],
  opportunityIds: string[],
  gradient: string,
  likesCount: number,
  bookmarksCount: number,
  daysAgo: number,
): CollectionSummary {
  return {
    id,
    owner_id: `sample-${owner}`,
    owner_username: owner,
    name: title,
    title,
    description,
    cover_image: null,
    cover_gradient: gradient,
    visibility: "public",
    is_published: true,
    tags,
    intended_majors,
    categories,
    opportunityIds,
    createdAt: now - (daysAgo + 9) * day,
    updatedAt: now - daysAgo * day,
    itemCount: opportunityIds.length,
    likesCount,
    bookmarksCount,
    likedByMe: false,
    bookmarkedByMe: false,
  };
}

