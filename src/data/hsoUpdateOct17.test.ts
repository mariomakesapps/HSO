describe("October 17 reviewed catalogue rules", () => {
  it.each(rules)("%s sets %s to the supplied value", (id, field, value) => {
    expect(allOpportunities.find(o => o.id === id)?.[field]).toEqual(value);
  });
  it.each(removed)("%s is hidden and permanently redirected", (id, target) => {
    expect(allOpportunities.some(o => o.id === id)).toBe(false);
    expect(REMOVED_OPPORTUNITY_REDIRECTS[id]).toBe(target);
  });
  it("preserves RSI's deadline because its update cell is blank", () => {
    expect(allOpportunities.find(o => o.id === "rsi")?.deadline).toBe("2026-12-11");
  });
  it("retains each new listing exactly once", () => {
    for (const id of [
  "mfa-boston-teen-arts-council",
  "high-museum-teen-leadership-council",
  "nga-teen-leadership-collective",
  "johns-hopkins-summer-jobs-program",
  "merit-health-leadership-academy"
]) {
      expect(allOpportunities.filter(o => o.id === id)).toHaveLength(1);
    }
  });
  it("does not expose malformed opening dates", () => {
    expect(opportunities.find(o => o.id === "university-of-texas-at-austin-summer-high-school-research-academ")?.opensAt).toBeNull();
  });
});
